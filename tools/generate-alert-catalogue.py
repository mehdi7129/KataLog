#!/usr/bin/env python3
"""Validate reviewed explanations and embed them in Swift, without runtime I/O.

Research JSON is the editable source of truth. --check detects stale Swift and
synthetic test fixtures. --coverage PATH explicitly opts in to a private corpus;
normal generation and CI never read the user's library or private telemetry.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'research/alerts'
OUTPUT = ROOT / 'Sources/KataLogCore/AlertCatalogueData.swift'
FIXTURE = ROOT / 'Tests/fixtures/synthetic/alert-catalogue.json'


def swift(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t') + '"'


def read_entries():
    entries = []
    for name in ('px4', 'vendor', 'marine'):
        payload = json.loads((DATA / name / 'catalogue.json').read_text())
        entries.extend(payload if isinstance(payload, list) else payload['entries'])
    ids = set()
    for entry in entries:
        key = entry['id']
        if key in ids or not re.fullmatch(r'[a-z0-9-]+', key):
            raise ValueError('Invalid/duplicate id: ' + key)
        ids.add(key)
        for field in ('title', 'meaning', 'limits', 'provenance'):
            if not isinstance(entry[field], str) or not entry[field].strip():
                raise ValueError(f'{key}: empty {field}')
        if not entry['checks'] or any(not s.strip() for s in entry['checks']):
            raise ValueError(key + ': missing checks')
        if entry['confidence'] not in ('documented', 'interpretation', 'unresolved'):
            raise ValueError(key + ': invalid specific confidence')
        if len(entry['meaning']) > 320:
            raise ValueError(key + ': meaning exceeds 320 characters; move technical detail to technicalDetails')
        if len(entry['title']) > 80:
            raise ValueError(key + ': title exceeds 80 characters')
        if 'technicalDetails' in entry and (not isinstance(entry['technicalDetails'], str) or not entry['technicalDetails'].strip()):
            raise ValueError(key + ': invalid technicalDetails')
        if not entry['patterns']:
            raise ValueError(key + ': missing patterns')
        for pattern in entry['patterns']:
            if not pattern.startswith('^') or not pattern.endswith('$'):
                raise ValueError(key + ': pattern must match a complete message')
            re.compile(pattern)
        examples = entry.get('syntheticExamples', [])
        if len(examples) != len(entry['patterns']):
            raise ValueError(key + ': one synthetic example is required per pattern')
        for pattern, example in zip(entry['patterns'], examples):
            if not isinstance(example, str) or not re.fullmatch(pattern, example, re.I):
                raise ValueError(key + ': synthetic example does not match its pattern')
        for source in entry['sources']:
            url = urlparse(source['url'])
            if url.scheme != 'https' or not url.netloc or not source['title'].strip():
                raise ValueError(key + ': invalid source link')
        document = entry.get('documentReference', {})
        has_document = (bool(document.get('title')) and bool(document.get('page'))
                        and bool(re.fullmatch(r'[0-9a-f]{64}', document.get('sha256', ''))))
        if entry['confidence'] == 'documented' and not (entry['sources'] or has_document):
            raise ValueError(key + ': documented definition needs a source link or a pinned document')
    return entries


def generate(entries, contexts):
    lines = ['// Generated by tools/generate-alert-catalogue.py. Edit research/alerts/*/catalogue.json.',
             '// Definitions are compiled into both the app and CLI; no network or resource bundle is required.',
             'import Foundation', '', 'enum AlertCatalogueData {',
             '    static let moduleContexts: [String: String] = [']
    for module, meaning in sorted(contexts.items()):
        lines.append(f'        {swift(module)}: {swift(meaning)},')
    lines += ['    ]', '', '    static let entries: [AlertCatalogueEntry] = [']
    for entry in entries:
        sources = ', '.join(f'AlertSource(title: {swift(s["title"])}, url: URL(string: {swift(s["url"])})!)' for s in entry['sources'])
        firmware = swift(entry['referenceFirmware']) if entry.get('referenceFirmware') else 'nil'
        details = swift(entry['technicalDetails']) if entry.get('technicalDetails') else 'nil'
        lines += ['        AlertCatalogueEntry(',
                  '            patterns: [' + ', '.join(map(swift, entry['patterns'])) + '],',
                  '            explanation: AlertExplanation(',
                  f'                id: {swift(entry["id"])}, title: {swift(entry["title"])},',
                  f'                meaning: {swift(entry["meaning"])},',
                  '                checks: [' + ', '.join(map(swift, entry['checks'])) + '],',
                  f'                limits: {swift(entry["limits"])},',
                  f'                provenance: {swift(entry["provenance"])},',
                  f'                sources: [{sources}], confidence: .{entry["confidence"]},',
                  f'                referenceFirmware: {firmware}, technicalDetails: {details})),']
    return '\n'.join(lines + ['    ]', '}', ''])


def synthetic_fixture(entries):
    payload = {
        'schemaVersion': 1,
        'provenance': 'Artificial examples constructed from catalogue patterns; no flight telemetry, frequencies, firmware distribution or private identifiers.',
        'examples': [
            {'id': entry['id'], 'patternIndex': index, 'text': example,
             'confidence': entry['confidence']}
            for entry in entries
            for index, example in enumerate(entry['syntheticExamples'])
        ],
        'fallbacks': [
            {'text': '[dance] 0', 'confidence': 'context'},
            {'text': '[ekf2] Synthetic future estimator message', 'confidence': 'context'},
            {'text': 'Synthetic unknown fault', 'confidence': 'raw'},
        ],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + '\n'


def coverage(entries, corpus_path, output_path=None):
    payload = json.loads(corpus_path.read_text())
    rules = [(e, [re.compile(p, re.I) for p in e['patterns']]) for e in entries]
    totals = {name: Counter() for name in ('all', 'alerts')}
    uncovered = []
    unresolved = []
    overlaps = []
    for message in payload['messages']:
        hits = [entry for entry, regexes in rules if any(r.fullmatch(message['text'].strip()) for r in regexes)]
        confidence = hits[0]['confidence'] if hits else 'without_matching_entry'
        for name in (('all', 'alerts') if message['is_alert'] else ('all',)):
            totals[name]['occurrences'] += message['occurrences']
            totals[name]['sourceVariants'] += message['source_variants']
            totals[name][confidence + 'Occurrences'] += message['occurrences']
            totals[name][confidence + 'SourceVariants'] += message['source_variants']
        if not hits:
            uncovered.append({k: message[k] for k in ('text', 'level', 'is_alert', 'occurrences', 'source_variants')})
        elif confidence == 'unresolved':
            unresolved.append({k: message[k] for k in ('text', 'level', 'is_alert', 'occurrences', 'source_variants')})
        if len(hits) > 1:
            overlaps.append({'text': message['text'], 'ids': [e['id'] for e in hits]})
    for counts in totals.values():
        for unit in ('Occurrences', 'SourceVariants'):
            counts['withoutEstablishedMeaning' + unit] = counts['unresolved' + unit] + counts['without_matching_entry' + unit]
            counts['establishedMeaning' + unit] = counts['documented' + unit] + counts['interpretation' + unit]
    result = {'catalogueVersion': 3, 'entries': len(entries),
              'patterns': sum(len(e['patterns']) for e in entries),
              'definitionsByConfidence': dict(Counter(e['confidence'] for e in entries)),
              'uniqueSourceURLs': len({s['url'] for e in entries for s in e['sources']}),
              'corpusObservedAt': payload['summary']['observed_at_utc'],
              'coverage': {k: dict(v) for k, v in totals.items()},
              'overlaps': overlaps, 'withoutMatchingEntry': uncovered,
              'unresolvedMessages': unresolved,
              'withoutSpecificDefinition': uncovered + unresolved}
    if output_path is not None:
        output_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k: v for k, v in result.items() if k not in ('overlaps', 'withoutSpecificDefinition', 'withoutMatchingEntry', 'unresolvedMessages')}, ensure_ascii=False))
    print(f'Without established meaning: {len(uncovered) + len(unresolved)} anonymized variants '
          f'({len(unresolved)} recognized but unresolved, {len(uncovered)} without catalogue rule); overlaps: {len(overlaps)}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--coverage', type=Path, metavar='PRIVATE_CORPUS',
                        help='Explicit opt-in: measure an existing private messages JSON')
    parser.add_argument('--coverage-output', type=Path, metavar='PRIVATE_REPORT',
                        help='Optional private output; otherwise print aggregate counts only')
    args = parser.parse_args()
    if args.coverage_output and not args.coverage:
        parser.error('--coverage-output requires --coverage PRIVATE_CORPUS')
    entries = read_entries()
    contexts = json.loads((DATA / 'module-contexts.json').read_text())
    output = generate(entries, contexts)
    fixture = synthetic_fixture(entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            sys.exit('Generated Swift is stale. Run python3 tools/generate-alert-catalogue.py')
        if not FIXTURE.exists() or FIXTURE.read_text() != fixture:
            sys.exit('Synthetic fixture is stale. Run python3 tools/generate-alert-catalogue.py')
        print(f'Catalogue validated: {len(entries)} entries; generated Swift and synthetic fixture are current.')
    else:
        OUTPUT.write_text(output)
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(fixture)
        print(f'Generated {len(entries)} reviewed explanations.')
    if args.coverage:
        coverage(entries, args.coverage, args.coverage_output)


if __name__ == '__main__':
    main()
